#ifndef KRONKNET_MACROS_TYPES_H
    #define KRONKNET_MACROS_TYPES_H
    #include <stdint.h>

    #define KNBUFFSIZ 8192

    ///////////////////////////////////////////////////////////////////////////
    /**
     * @brief Boolean defintion
     */
    //////////////////////////////////////////////////////////////////////////
    typedef int knBool;
    #define knTrue  1
    #define knFalse 0
    ///////////////////////////////////////////////////////////////////////////


    ///////////////////////////////////////////////////////////////////////////
    /**
     * @brief Port defintion
    */
    ///////////////////////////////////////////////////////////////////////////
    typedef unsigned short int knPort;
    ///////////////////////////////////////////////////////////////////////////


    ///////////////////////////////////////////////////////////////////////////
    /**
     * @brief Socket definition
     *
     * @note    On Windows a socket is a SOCKET (a UINT_PTR), and an invalid one
     *          is INVALID_SOCKET, not -1. Spelled without <winsock2.h>, which
     *          has no business in the headers of who uses kronknet
    */
    ///////////////////////////////////////////////////////////////////////////
    #ifdef _WIN32
        typedef uintptr_t knSocket;
        #define KN_INVALID_SOCKET (~(knSocket)0)
    #else
        typedef int knSocket;
        #define KN_INVALID_SOCKET (-1)
    #endif /* _WIN32 */
    ///////////////////////////////////////////////////////////////////////////


    ///////////////////////////////////////////////////////////////////////////
    /**
     * @brief ssize_t, which MSVC does not have (POSIX and MinGW do)
     */
    ///////////////////////////////////////////////////////////////////////////
    #if defined(_MSC_VER) && !defined(_SSIZE_T_DEFINED)
        typedef intptr_t ssize_t;
        #define _SSIZE_T_DEFINED
    #elif !defined(_MSC_VER)
        #include <sys/types.h>
    #endif /* _MSC_VER */
    ///////////////////////////////////////////////////////////////////////////


    ///////////////////////////////////////////////////////////////////////////
    /**
     * @brief Log level definition
     */
    ///////////////////////////////////////////////////////////////////////////
    typedef enum kronknet_log_level_e {

        knLogTrace = 0,  //!< Level trace
        knLogDebug,      //!< Level debug
        knLogInfo,       //!< Level info
        knLogWarn,       //!< Level warning
        knLogError,      //!< Level error
        knLogFatal,      //!< Level fatal

        knLogNone,       //!< None, but useful to know enum size

    } knLogLevel;
    ///////////////////////////////////////////////////////////////////////////


    ///////////////////////////////////////////////////////////////////////////
    /**
     * @brief Supported protocol definition
     */
    ///////////////////////////////////////////////////////////////////////////
    typedef enum kronknet_flags_e {

        knTCP = 0x01,  //!< TCP protocol
        knUDP = 0x02,  //!< UDP protocol

    } knFlags;
    ///////////////////////////////////////////////////////////////////////////

#endif /* KRONKNET_MACROS_TYPES_H */
